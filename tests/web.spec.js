test('constructor genera un producto válido y explica alternativas fuera del margen', async ({ page }) => {
  await page.goto('/');
  await page.locator('.desktop-nav').getByRole('button', { name: 'Crear combinada' }).click();
  await page.locator('.sport-options').getByRole('button', { name: 'Fútbol' }).click();
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/parlays/build') && response.request().method() === 'POST');
  await page.locator('button[type="submit"]').click();
  const result = await (await responsePromise).json();
  expect(result.status).toBe('matched');
  const product = result.parlay.legs.reduce((value, leg) => value * leg.odds, 1);
  expect(Math.abs(result.parlay.totalOdds - product)).toBeLessThan(0.000001);
  expect(new Set(result.parlay.legs.map(leg => leg.eventId)).size).toBe(3);
  expect(new Set(result.parlay.legs.map(leg => leg.bookmakerKey)).size).toBe(1);
  await expect(page.getByRole('heading', { name: 'Una combinada a tu medida.' })).toBeVisible();
  await page.getByRole('spinbutton', { name: 'Cuota total objetivo' }).fill('50');
  await page.locator('button[type="submit"]').click();
  await expect(page.getByRole('heading', { name: 'No hay una coincidencia exacta.' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Alternativas fuera del margen solicitado' })).toBeVisible();
});

