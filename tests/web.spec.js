import { test, expect } from '@playwright/test';

test('pantalla inicial muestra propuestas ficticias, horarios locales, detalles y copia', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('Modo demostración', { exact: true })).toBeVisible();
  await expect(page.locator('.parlay-card')).toHaveCount(6);
  await expect(page.locator('.demo-pill').first()).toHaveText('DEMO');
  await expect(page.locator('.card-update').first()).toContainText('Hora de Chile');
  const first = page.locator('.parlay-card').first();
  await first.getByRole('button', { name: 'Ver detalles' }).click();
  await expect(first.getByText(/Probabilidad implícita/)).toBeVisible();
  await expect(first.getByText(/No hay estadísticas/).first()).toBeVisible();
  await first.getByRole('button', { name: 'Copiar combinada' }).click();
  await expect(page.getByRole('status')).toContainText('copiada');
  const clipboard = await page.evaluate(() => navigator.clipboard.readText());
  expect(clipboard).toContain('FICTICIOS');
  expect(clipboard).toContain('America/Santiago');
  expect(clipboard).toContain('Cuota total');
  expect(errors).toEqual([]);
});

