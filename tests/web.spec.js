test('chat conectado conserva propuesta para seguimiento y muestra filtros y resultados actualizados', async ({ page }) => {
  // Only the remote interpretation transport is controlled here. Proposals and replacements
  // are generated by the running API engine; no remote AI service is claimed by this test.
  let lastPrevious;
  let lastResult;
  await page.route('**/api/status', async route => {
    const response = await route.fetch();
    const data = await response.json();
    await route.fulfill({ json: { ...data, ai: { configured: true, model: 'Modelo de prueba de transporte' } } });
  });
  await page.route('**/api/chat', async route => {
    const request = route.request().postDataJSON();
    const replacing = request.message.includes('segundo');
    const removing = request.message.includes('quita');
    lastPrevious = request.previous;
    const filters = {
      ...request.filters, sports: removing ? ['basketball'] : ['tennis', 'basketball'],
      legCount: 4, targetOdds: 3, tolerance: 0.8,
    };
    const response = await page.request.post('/api/parlays/build', {
      data: { filters, ...(replacing ? { previous: request.previous, replaceIndex: 1 } : {}) },
    });
    lastResult = await response.json();
    await route.fulfill({ json: { message: 'Resultado del transporte de prueba sobre eventos ficticios.', filters, result: lastResult, mode: 'demo', aiMode: 'live', changes: removing ? ['sports'] : replacing ? ['selection:2'] : ['sports', 'legCount', 'targetOdds'] } });
  });
  await page.goto('/');
  await page.locator('.desktop-nav').getByRole('button', { name: 'Asistente IA' }).click();
  const textbox = page.getByRole('textbox', { name: 'Mensaje al asistente IA' });
  await textbox.fill('Combina tenis y básquetbol con 4 partidos y cuota 3,00');
  await page.getByRole('button', { name: 'Enviar mensaje' }).click();
  await expect(page.locator('.chat-entry.assistant')).toHaveCount(1);
  await expect(page.locator('.chat-entry.assistant').first().getByText('Filtros interpretados')).toBeVisible();
  expect(lastResult.status).toBe('matched');
  const first = lastResult.parlay;
  await textbox.fill('cambia el segundo partido');
  await page.getByRole('button', { name: 'Enviar mensaje' }).click();
  await expect(page.locator('.chat-entry.assistant')).toHaveCount(2);
  expect(lastPrevious.id).toBe(first.id);
  const changed = lastResult.parlay || lastResult.alternatives[0];
  expect(changed.legs[0].id).toBe(first.legs[0].id);
  expect(changed.legs[1].eventId).not.toBe(first.legs[1].eventId);
  await textbox.fill('quita el tenis');
  await page.getByRole('button', { name: 'Enviar mensaje' }).click();
  await expect(page.locator('.chat-entry.assistant')).toHaveCount(3);
  const removed = lastResult.parlay || lastResult.alternatives[0];
  expect(removed.legs.every(leg => leg.sport === 'basketball')).toBe(true);
  await expect(page.locator('.chat-entry.assistant').last().locator('.filter-summary').first()).toContainText('Básquetbol');
});

test('un fallo del proveedor se muestra y permite reintentar', async ({ page }) => {
  await page.route('**/api/parlays/daily?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Proveedor no disponible temporalmente.', code: 'PROVIDER_UNAVAILABLE' }) }));
  await page.goto('/');
  await expect(page.getByRole('alert')).toContainText('Proveedor no disponible temporalmente.');
  await expect(page.locator('.parlay-card')).toHaveCount(0);
  await page.unroute('**/api/parlays/daily?**');
  await page.getByRole('button', { name: /Reintentar/ }).click();
  await expect(page.locator('.parlay-card')).toHaveCount(6);
});

